"""
Regenerates the offline icon bundles used by the admin and web apps, so the
UI never has to fetch icons from api.iconify.design at runtime.

Usage: git clone --depth 1 --filter=blob:none --sparse https://github.com/iconify/icon-sets
       (sparse-checkout json/mdi.json json/solar.json), then
       python3 tools/build-icons.py /path/to/icon-sets/json
"""
import json, sys, pathlib

CATEGORY_ICONS = [
    'mdi:content-cut', 'mdi:razor-double-edge', 'mdi:face-man-shimmer', 'mdi:mustache',
    'mdi:hair-dryer', 'mdi:spa', 'mdi:lotion', 'mdi:face-mask', 'mdi:hand-back-right',
    'mdi:crown', 'mdi:account-child', 'mdi:palette', 'mdi:bottle-tonic', 'mdi:shower-head',
    'mdi:star-four-points', 'mdi:brush',
]
UI_ICONS = [
    'mdi:instagram', 'mdi:facebook', 'mdi:whatsapp',
    'solar:scissors-bold-duotone', 'solar:widget-5-bold-duotone', 'solar:list-bold-duotone',
    'solar:logout-2-bold-duotone', 'solar:add-circle-bold', 'solar:tag-price-bold-duotone',
    'solar:clock-circle-bold', 'solar:star-bold', 'solar:map-point-bold-duotone',
    'solar:phone-calling-bold-duotone', 'solar:letter-bold-duotone', 'solar:calendar-bold-duotone',
    'solar:magnifer-linear', 'solar:user-rounded-bold-duotone', 'solar:gallery-bold-duotone',
    'solar:arrow-right-linear', 'solar:star-bold-duotone', 'solar:medal-ribbons-star-bold-duotone',
    'solar:cup-star-bold-duotone', 'solar:smile-circle-bold-duotone', 'solar:hand-stars-bold-duotone',
    'solar:bill-list-bold-duotone', 'solar:chart-2-bold-duotone', 'solar:refresh-linear',
    'solar:danger-triangle-bold', 'solar:arrow-up-linear', 'solar:clock-circle-bold-duotone',
    'solar:alarm-bold-duotone',
]

src = pathlib.Path(sys.argv[1])
sets = {}
def get(name):
    prefix, icon = name.split(':')
    if prefix not in sets:
        sets[prefix] = json.loads((src / f'{prefix}.json').read_text())
    data = sets[prefix]
    entry = data['icons'].get(icon)
    if entry is None:
        alias = data['aliases'][icon]
        entry = data['icons'][alias['parent']]
    out = {'body': entry['body']}
    w = entry.get('width', data.get('width', 16)); h = entry.get('height', data.get('height', 16))
    if (w, h) != (24, 24):
        out['width'] = w; out['height'] = h
    return out

header = '// Generated by tools/build-icons.py — do not edit by hand.\n\n'
lines = [header, 'export const barberIcons = {\n']
for name in CATEGORY_ICONS + UI_ICONS:
    lines.append(f'  {json.dumps(name)}: {json.dumps(get(name))},\n')
lines.append('} as const;\n\n')
lines.append('/** Icons the admin can pick for a category; the landing page renders the same set. */\n')
lines.append('export const CATEGORY_ICONS = ' + json.dumps(CATEGORY_ICONS, indent=2).replace('"', "'").replace("]", "] as const;") + '\n')

root = pathlib.Path(__file__).resolve().parent.parent
for target in ['apps/admin/src/components/iconify/barber-icons.ts', 'apps/web/src/components/iconify/barber-icons.ts']:
    p = root / target
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(''.join(lines))
    print('wrote', target)
